import { canvasMockupHtml, CANVAS_MOCKUP_HTML_STYLES } from "./canvasMockupHtml";
import type { CanvasMockupBlock } from "@octant/contracts/canvas";

/**
 * One mockup variant as a dependency-free React component: the same semantic,
 * inert tree the HTML form generates, with the stylesheet inlined as one
 * style element, no imports, and no script. Pure and deterministic, so the
 * same definition always hands off the same bytes.
 */

const toComponentName = (value: string): string => {
  const part = value
    .split(/[^A-Za-z0-9]+/)
    .filter((piece) => piece.length > 0)
    .map((piece) => piece.charAt(0).toUpperCase() + piece.slice(1))
    .join("");
  return part.length === 0 ? "Mockup" : /^[A-Za-z]/.test(part) ? part : `Screen${part}`;
};

/** The generator's HTML, embedded verbatim: its text is already escaped for markup, and a JSX child reads the same entities a browser does. */
export function canvasMockupTsx(block: CanvasMockupBlock, variantId?: string | undefined): string {
  const html = canvasMockupHtml(block, {
    ...(variantId === undefined ? {} : { variantId }),
  });
  if (html === "") return "";
  const name =
    variantId === undefined
      ? toComponentName(block.title)
      : `${toComponentName(block.title)}${toComponentName(variantId)}`;
  const escaped = html;
  const styles = CANVAS_MOCKUP_HTML_STYLES.join("");
  return [
    "// Generated by Octant from a Canvas mockup. Dependency-free: no imports, no script.",
    `export function ${name}() {`,
    "  return (",
    `    <div>${escaped}</div>`,
    "  );",
    "}",
    "",
    `export const ${name}Styles = ${JSON.stringify(styles)};`,
    "",
  ].join("\n");
}
