import type { CanvasBlock } from "@octant/contracts/canvas";
import { CANVAS_MOCKUP_HTML_STYLES, canvasMockupHtml } from "./canvasMockupHtml";
import { canvasMockupFrames } from "./canvasMockupOutline";

/**
 * A Canvas's mockups as one dependency-free TSX module: every variant of every
 * mockup a component that draws the same semantic, inert tree the HTML form
 * generates, with the generated stylesheet rendered in a style element. No
 * imports (the automatic JSX runtime needs none), no script, no state. Pure
 * and deterministic, so the same definition always hands off the same bytes.
 */

/** Elements the generator writes that JSX must close itself. */
const VOID_ELEMENTS: ReadonlySet<string> = new Set(["input", "img", "br", "hr"]);

/**
 * The generator's markup as JSX. The markup is this module's own: every text
 * and attribute value went through the HTML escaper, so a `<` or `>` inside
 * one is already an entity and a tag can be read whole. JSX reads the same
 * entities a browser does; braces become entities because JSX would read a
 * bare one as an expression. A disabled control keeps its drawn state as a
 * default, so React draws it without asking for a change handler.
 */
function jsxFromMarkup(markup: string): string {
  return markup
    .replaceAll("{", "&#123;")
    .replaceAll("}", "&#125;")
    .replace(/<([a-z][a-z0-9]*)((?:\s[^>]*)?)>/g, (_tag, name: string, attributes: string) => {
      let jsx = attributes.replace(/\sclass="/g, ' className="');
      if (name === "input") {
        jsx = jsx.replace(/\schecked(?=[\s>]|$)/g, " defaultChecked");
        jsx = jsx.replace(/\svalue="/g, ' defaultValue="');
      }
      return VOID_ELEMENTS.has(name) ? `<${name}${jsx.trimEnd()} />` : `<${name}${jsx}>`;
    });
}

/** A component name from a title: its words, capitalized and joined. */
function componentWords(value: string): string {
  return value
    .split(/[^A-Za-z0-9]+/)
    .filter((piece) => piece.length > 0)
    .map((piece) => piece.charAt(0).toUpperCase() + piece.slice(1))
    .join("");
}

/** The handed-off module, or nothing when the Canvas holds no mockup to draw. */
export function canvasMockupsTsx(blocks: ReadonlyArray<CanvasBlock>): string | undefined {
  const taken = new Set<string>(["mockupStyles"]);
  const unique = (wanted: string): string => {
    const base = /^[A-Za-z]/.test(wanted) ? wanted : `Screen${wanted}`;
    let name = base;
    for (let index = 2; taken.has(name); index += 1) name = `${base}${String(index)}`;
    taken.add(name);
    return name;
  };
  const components: string[] = [];
  for (const block of blocks) {
    if (block.kind !== "mockup") continue;
    const mockup = block;
    for (const frame of canvasMockupFrames(mockup)) {
      const html = canvasMockupHtml(
        mockup,
        frame.label === undefined ? {} : { variantId: frame.key },
      );
      if (html === "") continue;
      const name = unique(componentWords(`${mockup.title} ${frame.label ?? ""}`) || "Mockup");
      components.push(
        [
          `export function ${name}() {`,
          "  return (",
          "    <div>",
          "      <style>{mockupStyles}</style>",
          `      ${jsxFromMarkup(html)}`,
          "    </div>",
          "  );",
          "}",
        ].join("\n"),
      );
    }
  }
  if (components.length === 0) return undefined;
  return [
    "// Generated by Octant from a Canvas's mockups. Dependency-free: no imports, no script.",
    `const mockupStyles = ${JSON.stringify(CANVAS_MOCKUP_HTML_STYLES.join(""))};`,
    "",
    components.join("\n\n"),
    "",
  ].join("\n");
}
