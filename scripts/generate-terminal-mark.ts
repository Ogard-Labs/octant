import { readFile, writeFile } from "node:fs/promises";

/** Sample the brand blade and its seven rotations through the sprite's shear. */
export function terminalMarkFromSprite(svg: string): string {
  const symbol = /<symbol id="aperture"[\s\S]*?<\/symbol>/.exec(svg)?.[0];
  const path = symbol === undefined ? undefined : /<path id="blade" d="([^"]+)"/.exec(symbol)?.[1];
  const matrix =
    symbol === undefined
      ? undefined
      : /matrix\(([^)]+)\)/.exec(symbol)?.[1]?.split(/\s+/).map(Number);
  if (path === undefined || matrix?.length !== 6)
    throw new Error("Aperture geometry is unavailable.");
  const [a = 1, b = 0, c = 0, d = 1, e = 0, f = 0] = matrix;
  const tokens = path.match(/[MLAZ]|-?\d*\.?\d+/g) ?? [];
  const vertices: [number, number][] = [];
  // Rounded corners are smaller than a pixel at this size. Their endpoints
  // bound the blade; subpixel coverage retains the shear and blade gaps.
  for (let i = 0; i < tokens.length;) {
    const command = tokens[i++];
    if (command === "Z") break;
    const count = command === "A" ? 7 : command === "M" || command === "L" ? 2 : 0;
    if (count === 0) throw new Error("Unsupported aperture path command.");
    const numbers = tokens.slice(i, i + count).map(Number);
    i += count;
    const x = numbers[count - 2],
      y = numbers[count - 1];
    if (x === undefined || y === undefined || !Number.isFinite(x) || !Number.isFinite(y))
      throw new Error("Invalid aperture coordinates.");
    vertices.push([x, y]);
  }
  const polygons = Array.from({ length: 8 }, (_, index) => {
    const angle = (index * Math.PI) / 4;
    return vertices.map(([x, y]): [number, number] => {
      const rx = x * Math.cos(angle) - y * Math.sin(angle),
        ry = x * Math.sin(angle) + y * Math.cos(angle);
      return [a * rx + c * ry + e, b * rx + d * ry + f];
    });
  });
  const inside = (x: number, y: number, polygon: readonly [number, number][]) => {
    let hit = false;
    for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
      const [xi = 0, yi = 0] = polygon[i] ?? [],
        [xj = 0, yj = 0] = polygon[j] ?? [];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
    }
    return hit;
  };
  const pixel = (x: number, y: number) => {
    let count = 0;
    for (let sy = 0; sy < 4; sy++)
      for (let sx = 0; sx < 4; sx++) {
        if (
          polygons.some((polygon) =>
            inside(((x + (sx + 0.5) / 4) * 100) / 24, ((y + (sy + 0.5) / 4) * 100) / 24, polygon),
          )
        )
          count++;
      }
    return count >= 5;
  };
  return Array.from({ length: 12 }, (_, row) =>
    Array.from({ length: 24 }, (_, x) => {
      const top = pixel(x, row * 2),
        bottom = pixel(x, row * 2 + 1);
      return top ? (bottom ? "█" : "▀") : bottom ? "▄" : " ";
    })
      .join("")
      .trimEnd(),
  ).join("\n");
}
if (import.meta.main) {
  const mark = terminalMarkFromSprite(
    await readFile(new URL("../apps/web/public/icons.svg", import.meta.url), "utf8"),
  );
  await writeFile(
    new URL("../packages/cli/src/agentTuiMark.ts", import.meta.url),
    `// Generated by scripts/generate-terminal-mark.ts from icons.svg#aperture, including its shear.\nexport const agentTuiMark = ${JSON.stringify(mark)};\n`,
  );
}
